/** The Postmark API (https, no redirects). */
export const POSTMARK_API_BASE_URL = 'https://api.postmarkapp.com';
/** The token a spec replaces `fetch` with. */
export const POSTMARK_FETCH = 'POSTMARK_FETCH';
const TIMEOUT_MS = 15_000;
/** How long a delivered Postmark message id is remembered (single use). */
const DELIVERY_TTL_MS = 60 * 60 * 1000;

export type PostmarkFetch = (url: string, init: RequestInit) => Promise<Response>;

/** A Postmark API error (status + Postmark's error code; never the token). */
export class PostmarkApiError extends Error {
	constructor(
		readonly status: number,
		readonly code: number | string,
		message: string
	) {
		super(message);
		this.name = 'PostmarkApiError';
	}
}

interface PostmarkAddress {
	Email?: string;
	Name?: string;
	MailboxHash?: string;
}

/** Postmark's inbound webhook body (the parts the plugin reads). */
export interface PostmarkInboundMessage {
	MessageID?: string;
	From?: string;
	FromName?: string;
	FromFull?: PostmarkAddress;
	ToFull?: PostmarkAddress[];
	CcFull?: PostmarkAddress[];
	BccFull?: PostmarkAddress[];
	OriginalRecipient?: string;
	ReplyTo?: string;
	Subject?: string;
	Date?: string;
	TextBody?: string;
	HtmlBody?: string;
	Headers?: Array<{ Name?: string; Value?: string }>;
	Attachments?: Array<{
		Name?: string;
		Content?: string;
		ContentType?: string;
		ContentLength?: number;
		ContentID?: string;
	}>;
	/** The raw message, when the inbound stream includes it. */
	RawEmail?: string;
}

const address = (entry: PostmarkAddress | undefined): IInboundEmailAddress | undefined => {
	if (!entry?.Email || !entry.Email.includes('@')) return undefined;
	return entry.Name ? { address: entry.Email, name: entry.Name } : { address: entry.Email };
};
const addresses = (entries: PostmarkAddress[] | undefined): IInboundEmailAddress[] =>
	(Array.isArray(entries) ? entries : []).map(address).filter((entry): entry is IInboundEmailAddress => !!entry);

/** Constant-time equality of two strings (length leaks nothing useful here: both are fixed-length digests). */
function sameSecret(a: string, b: string): boolean {
	const left = createHash('sha256').update(a, 'utf8').digest();
	const right = createHash('sha256').update(b, 'utf8').digest();
	return timingSafeEqual(left, right);
}

/**
 * Postmark (plan 04 §5.2, G-P4-7).
 *
 * - **Inbound.** Postmark posts the whole message as JSON to the inbound webhook URL. Postmark does not sign webhooks,
 *   so the account carries a **random Basic-auth credential**, generated by the server and shown once, which the URL
 *   includes (`https://<user>:<password>@…/api/inbox/inbound/postmark/<account id>`); a request without it, or with
 *   another one, is refused (constant-time compare). There is no unsigned mode. The Postmark message id makes a
 *   delivery single use. `RawEmail`, when the stream includes it, is parsed as MIME instead of the JSON fields.
 * - **Outbound.** A nodemailer transport over `POST /email` with the server token.
 * - **Test connection.** `GET /server` with the server token.
 */
@Injectable()
export class PostmarkProvider implements IEmailProviderPlugin, IInboundEmailProvider, OnModuleInit, OnModuleDestroy {
	readonly id = 'postmark';
	readonly displayName = 'Postmark';
	readonly description = 'Receive with a Postmark inbound stream and send through the Postmark API.';
	readonly capabilities = { inbound: true, outbound: true, customDomains: true };
	readonly configSchema = {
		type: 'object' as const,
		properties: {
			serverToken: {
				type: 'string' as const,
				title: 'Server API token',
				description: 'The Postmark server token (sending and the connection test).',
				writeOnly: true
			},
			webhookUser: {
				type: 'string' as const,
				title: 'Webhook user',
				description: 'Generated: part of the inbound webhook URL’s Basic-auth credential.',
				generated: true
			},
			webhookPassword: {
				type: 'string' as const,
				title: 'Webhook password',
				description: 'Generated: part of the inbound webhook URL’s Basic-auth credential (shown once).',
				generated: true
			},
			fromAddress: {
				type: 'string' as const,
				title: 'Default sender',
				description: 'A confirmed sender signature or an address on a verified domain.',
				format: 'email' as const
			},
			messageStream: {
				type: 'string' as const,
				title: 'Message stream',
				description: 'The outbound message stream (default "outbound").',
				maxLength: 100,
				pattern: '^[a-z0-9-]+$',
				default: 'outbound'
			}
		},
		required: ['webhookUser', 'webhookPassword']
	};
	readonly inbound: IInboundEmailProvider = this;
	private readonly logger = new Logger(PostmarkProvider.name);

	constructor(
		@Optional() @Inject(INBOX_EMAIL_PROVIDER_REGISTRY) private readonly registry?: IEmailProviderRegistry,
		@Optional() @Inject(POSTMARK_FETCH) private readonly fetcher?: PostmarkFetch
	) {}

	onModuleInit(): void {
		if (!this.registry) {
			this.logger.warn(
				'The Inbox email features are off (GAUZY_INBOX_EMAIL_ENABLED): the Postmark provider stays idle.'
			);
			return;
		}
		this.registry.register(this);
	}

	onModuleDestroy(): void {
		this.registry?.unregister(this.id);
	}

	/** The account URL with its Basic-auth credential (answered once, when the credential is generated). */
	webhookUrl(baseUrl: string, account: IProviderAccountContext): string {
		const url = new URL(baseUrl);
		url.username = encodeURIComponent(String(account.config['webhookUser'] ?? ''));
		url.password = encodeURIComponent(String(account.config['webhookPassword'] ?? ''));
		return url.toString();
	}

	async verify(request: IInboundWebhookRequest, account: IProviderAccountContext): Promise<IInboundDeliveryIdentity> {
		const user = String(account.config['webhookUser'] ?? '');
		const password = String(account.config['webhookPassword'] ?? '');
		const raw = request.headers['authorization'];
		const header = (Array.isArray(raw) ? raw[0] : raw) ?? '';
		const match = /^Basic\s+([A-Za-z0-9+/=]+)\s*$/i.exec(header);
		const presented = match ? Buffer.from(match[1] as string, 'base64').toString('utf8') : '';
		if (!user || !password || !presented || !sameSecret(presented, `${user}:${password}`)) {
			throw new UnauthorizedException('The Postmark webhook does not carry this account’s credential.');
		}
		const body = (request.body ?? {}) as PostmarkInboundMessage;
		// The delivery: Postmark's message id (else the body), single use in the pipeline.
		const fingerprint =
			typeof body.MessageID === 'string' && body.MessageID
				? `id:${body.MessageID}`
				: `body:${createHash('sha256')
						.update(request.rawBody ?? Buffer.alloc(0))
						.digest('hex')}`;
		return { fingerprint, ttlMs: DELIVERY_TTL_MS };
	}

	async parse(request: IInboundWebhookRequest): Promise<ParsedInboundEmail[]> {
		const body = (request.body ?? {}) as PostmarkInboundMessage;
		if (typeof body !== 'object' || (!body.FromFull && !body.From && !body.RawEmail)) return [];
		const headers: Record<string, string> = {};
		for (const entry of Array.isArray(body.Headers) ? body.Headers : []) {
			if (entry?.Name && typeof entry.Value === 'string')
				headers[entry.Name.toLowerCase()] = entry.Value.slice(0, 1000);
		}
		const envelopeRecipients =
			typeof body.OriginalRecipient === 'string' && body.OriginalRecipient ? [body.OriginalRecipient] : [];
		// Only what Postmark's own servers add is trusted: `Received-SPF` and the SpamAssassin score. A sender can put
		// any `Authentication-Results` into its message, so no DKIM / DMARC verdict is taken from it (an allowlisted
		// mailbox therefore admits no Postmark mail: allowlists need a DMARC verdict the relay vouches for).
		const verdicts: { dkim?: ReturnType<typeof toVerdict>; dmarc?: ReturnType<typeof toVerdict> } = {};
		const spf = toVerdict(/^(pass|fail|softfail|neutral|none)/i.exec(headers['received-spf'] ?? '')?.[1]);
		const score = Number.parseFloat(headers['x-spam-score'] ?? '');
		const receivedAt = body.Date ? new Date(body.Date) : new Date();
		const when = Number.isNaN(receivedAt.getTime()) ? new Date() : receivedAt;
		const extra = {
			envelopeRecipients,
			receivedAt: when,
			...(spf ? { spf } : {}),
			...(verdicts.dkim ? { dkim: verdicts.dkim } : {}),
			...(verdicts.dmarc ? { dmarc: verdicts.dmarc } : {}),
			...(Number.isFinite(score) ? { spamScore: score } : {}),
			...(body.MessageID ? { providerMessageId: body.MessageID } : {})
		};
		if (typeof body.RawEmail === 'string' && body.RawEmail) {
			return [await parseMimeMessage(Buffer.from(body.RawEmail, 'utf8'), extra)];
		}

		const attachments: IParsedInboundAttachment[] = (Array.isArray(body.Attachments) ? body.Attachments : [])
			.map((attachment) => {
				const content = Buffer.from(attachment?.Content ?? '', 'base64');
				const contentId = attachment?.ContentID?.replace(/^<|>$/g, '');
				return {
					filename: safeFilename(attachment?.Name),
					...(attachment?.ContentType ? { contentType: attachment.ContentType } : {}),
					size: content.length,
					content,
					...(contentId ? { contentId, isInline: true } : { isInline: false })
				};
			})
			.filter((attachment) => attachment.size > 0);
		const from = address(body.FromFull) ?? (body.From ? { address: body.From } : undefined);
		const replyTo = body.ReplyTo ? [{ address: body.ReplyTo }] : [];
		const messageId =
			messageIdOf(headers['message-id']) ?? derivedMessageId(request.rawBody ?? JSON.stringify(body));
		const inReplyTo = messageIdOf(headers['in-reply-to']);
		const text = typeof body.TextBody === 'string' && body.TextBody ? body.TextBody : undefined;
		const html = typeof body.HtmlBody === 'string' && body.HtmlBody ? body.HtmlBody : undefined;
		return [
			{
				messageId,
				...(body.MessageID ? { providerMessageId: body.MessageID } : {}),
				...(from ? { from } : {}),
				to: addresses(body.ToFull),
				cc: addresses(body.CcFull),
				replyTo,
				envelopeRecipients,
				...(body.Subject ? { subject: body.Subject } : {}),
				...(text ? { text } : {}),
				...(html ? { html } : {}),
				...(inReplyTo ? { inReplyTo } : {}),
				references: referencesOf(headers['references']),
				headers,
				receivedAt: when,
				sizeBytes: request.rawBody?.length ?? 0,
				...(extra.spf ? { spf: extra.spf } : {}),
				...(extra.dkim ? { dkim: extra.dkim } : {}),
				...(extra.dmarc ? { dmarc: extra.dmarc } : {}),
				...(extra.spamScore !== undefined ? { spamScore: extra.spamScore } : {}),
				attachments
			}
		];
	}

	createTransport(account: IProviderAccountContext): unknown {
		const token = this.token(account);
		const stream =
			typeof account.config['messageStream'] === 'string'
				? (account.config['messageStream'] as string)
				: 'outbound';
		const from =
			typeof account.config['fromAddress'] === 'string' ? (account.config['fromAddress'] as string) : undefined;
		return providerTransport(
			'postmark',
			async (mail) => {
				const answer = await this.call<{ MessageID?: string; ErrorCode?: number; Message?: string }>(
					token,
					'POST',
					'/email',
					{
						From: formatAddress(mail.from),
						To: mail.to.map(formatAddress).join(', '),
						...(mail.cc.length ? { Cc: mail.cc.map(formatAddress).join(', ') } : {}),
						...(mail.bcc.length ? { Bcc: mail.bcc.map(formatAddress).join(', ') } : {}),
						...(mail.replyTo.length ? { ReplyTo: mail.replyTo.map(formatAddress).join(', ') } : {}),
						Subject: mail.subject,
						...(mail.html ? { HtmlBody: mail.html } : {}),
						...(mail.text ? { TextBody: mail.text } : {}),
						Headers: Object.entries(mail.headers).map(([Name, Value]) => ({ Name, Value })),
						...(mail.attachments.length
							? {
									Attachments: mail.attachments.map((attachment) => ({
										Name: attachment.filename,
										Content: attachment.content.toString('base64'),
										ContentType: attachment.contentType ?? 'application/octet-stream',
										...(attachment.cid ? { ContentID: `cid:${attachment.cid}` } : {})
									}))
								}
							: {}),
						MessageStream: stream
					}
				);
				if (!answer?.MessageID)
					throw new PostmarkApiError(
						502,
						answer?.ErrorCode ?? 'invalid_response',
						'Postmark accepted the email without an id.'
					);
				return { id: answer.MessageID };
			},
			from
		);
	}

	async verifyAccount(account: IProviderAccountContext): Promise<{ ok: boolean; message?: string }> {
		try {
			const server = await this.call<{ Name?: string; InboundAddress?: string }>(
				this.token(account),
				'GET',
				'/server'
			);
			return {
				ok: true,
				message: `Connected to the Postmark server "${String(server?.Name ?? '').slice(0, 100)}".`
			};
		} catch (error) {
			if (error instanceof PostmarkApiError && error.status === 401)
				return { ok: false, message: 'Postmark refused the server token.' };
			return {
				ok: false,
				message: error instanceof Error ? error.message.slice(0, 300) : 'The connection test failed.'
			};
		}
	}

	private token(account: IProviderAccountContext): string {
		const token =
			typeof account.config['serverToken'] === 'string' ? (account.config['serverToken'] as string) : '';
		if (!token) throw new PostmarkApiError(0, 'missing_token', 'The Postmark account has no server token.');
		return token;
	}

	private async call<T>(token: string, method: 'GET' | 'POST', path: string, body?: unknown): Promise<T> {
		const fetcher = this.fetcher ?? ((url: string, init: RequestInit) => fetch(url, init));
		const response = await fetcher(`${POSTMARK_API_BASE_URL}${path}`, {
			method,
			redirect: 'error',
			signal: AbortSignal.timeout(TIMEOUT_MS),
			headers: {
				Accept: 'application/json',
				'X-Postmark-Server-Token': token,
				...(body !== undefined ? { 'Content-Type': 'application/json' } : {})
			},
			...(body !== undefined ? { body: JSON.stringify(body) } : {})
		});
		const text = await response.text();
		let data: unknown = null;
		try {
			data = text ? JSON.parse(text) : null;
		} catch {
			data = null;
		}
		const error = (data ?? {}) as { ErrorCode?: number; Message?: string };
		if (!response.ok || (typeof error.ErrorCode === 'number' && error.ErrorCode !== 0)) {
			throw new PostmarkApiError(
				response.status,
				error.ErrorCode ?? 'http_error',
				typeof error.Message === 'string'
					? error.Message.slice(0, 300)
					: `Postmark answered ${response.status}.`
			);
		}
		return data as T;
	}
}
